# 环节：领域契约层；用途：定义业务数据模型与可替换端口，不依赖具体基础设施。
"""Replace adapters without changing graph/runtime code."""

from typing import Protocol


class ModelUnavailable(RuntimeError):
    """Raised by model gateways with a stable machine-readable code as first arg."""


class ModelGateway(Protocol):
    configured: bool

    async def json(self, system: str, payload: dict, schema: dict) -> dict: ...


class EvaluationRepository(Protocol):
    async def initialize(self) -> None: ...
    async def save_session(self, session: dict) -> None: ...
    async def history(self, session: dict, limit: int = 20) -> list[dict]: ...
    async def create_run(self, state: dict) -> None: ...
    async def get_run(self, run_id: str) -> dict | None: ...
    async def claim(self, run_id: str, owner: str, seconds: float) -> bool: ...
    async def checkpoint(self, state: dict, owner: str) -> None: ...
    async def release(self, run_id: str, owner: str) -> None: ...


class KnowledgeSource(Protocol):
    async def search(self, query: str, metric_ids: list[str]) -> list[dict]: ...
